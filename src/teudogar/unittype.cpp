void
unscramble(char *s, int n)
{
	char key;
	int len, m, i;

	key = s[n - 2];
	len = (unsigned char)s[n - 1];
	m = len < n - 2 ? len : n - 2;
	for (i = 0; i < m; i++)
		s[i] ^= key;
}

void
unscrambleall(void)
{
	unscramble(udstr0, sizeof udstr0);
	unscramble(udstr1, sizeof udstr1);
	unscramble(udstr2, sizeof udstr2);
	unscramble(udstr3, sizeof udstr3);
	udtaid ^= 0xffff;
}

void
scramble(char *dst, char *src, int n)
{
	int len, pad, i;
	int r;
	char key;

	len = 0;
	while (src[len])
		len++;
	len++;
	if (len > n - 2)
		len = n - 2;
	key = randn(255);
	for (i = 0; i < len; i++)
		dst[i] = src[i] ^ key;
	pad = randn(n - 5);
	for (; i < pad && i < n - 2; i++) {
		r = randn(255);
		dst[i] = r;
	}
	dst[n - 2] = key;
	dst[n - 1] = len;
}

int
loadudta(void)
{
	DWORD *w;
	DWORD crc, n, sum, id;
	char *p;
	int ok;

	memset(tmpbuf, 0, sizeof tmpbuf);
	w = (DWORD *)(udtablob + 8);
	crc = *w++;
	n = *w++;
	ok = 1;
	if (n > 0x113) {
		logf("Udta len == %d, siz(udta) == %d", sizeof udtablob);
		ok = 0;
	} else if (n == 0) {
		logf("Udta len == 0");
		ok = 0;
	} else {
		sum = crcbuf(w, n);
		if (sum != crc) {
			logf("Udta Csum Fehler soll %X, ist %X", crc, sum);
			ok = 0;
		}
		invert((char *)w, n);
		if (unpack(tmpbuf, sizeof tmpbuf, w, n) == 0) {
			logf("Udta Decompr %d Bytes versucht: Fehler", n);
			ok = 0;
			memset(tmpbuf, 0, sizeof tmpbuf);
		}
	}
	id = *(int *)tmpbuf;
	id ^= 0xffff;
	udtaid = id;
	p = tmpbuf;
	p += 5;
	scramble(udstr0, *p ? p : "", sizeof udstr0);
	while (*p)
		p++;
	p++;
	scramble(udstr1, *p ? p : "", sizeof udstr1);
	while (*p)
		p++;
	p++;
	scramble(udstr2, *p ? p : "", sizeof udstr2);
	while (*p)
		p++;
	p++;
	scramble(udstr3, *p ? p : "", sizeof udstr3);
	while (*p)
		p++;
	udtaok = 1;
	return ok;
}

