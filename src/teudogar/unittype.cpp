short
checkstandanim(Unit *u)
{
	if (badunit(u))
		return 0;
	if (u->pose < 20 || u->pose > 27)
		return 1;
	ctacls = partof(u)->anim;
	if (ctacls == 7 && (u->pose == 22 || u->pose == 23)) {
		if (!isfield(map[u->x + u->y * 150]))
			goto clr;
	}
	if (ctacls == 2 || ctacls == 3 || ctacls == 7) {
		if (u->pose == 20 && u->diry == 1) {
			if (u->beltkind)
				goto clr;
			if (u->handkind && u->mode != 20 && u->mode != 22)
				goto clr;
			if (islittorch(u->offhand))
				goto clr;
			if (ctacls == 2 && u->offhand != 0)
				goto clr;
		}
	}
	if (hasgearbank == 1 && partof(u)->showbody && ctacls != 1) {
		if (u->pose == 22 || u->pose == 23 || u->pose == 24 || u->pose == 25) {
			ctawear = u->body & 0xfff;
			if (!(ctawear == 0 || ctawear == 0x1ad || ctawear == 0x1b5))
				goto clr;
			ctawear = u->legs & 0xfff;
			if (!(ctawear == 0 || ctawear == 0x1a0))
				goto clr;
		}
	}
	if (hasgearbank == 1 && ctacls == 6) {
		if (u->pose == 24 || u->pose == 25) {
			if (u->cloak != 0 || u->head != 0)
				goto clr;
		}
	}
	return 1;
clr:
	u->pose = 0;
	return 0;
}

int
corpseitem(Unit *u)
{
	int d;

	if (badunit(u))
		return 0x825;
	if (isanimal(u) || u->health > 0)
		goto base;
	d = gameday - u->plea;
	if (d >= 14)
		ciword = 0x825;
	else if (d >= 3)
		ciword = 0x84c;
	else
		goto base;
	goto check;
base:
	ciword = u->part;
	ciword = ((Recipe *)(recipes + 0x20))[ciword].corpse + 0x820;
	if (isanimal(u))
		goto adjust;
	if (isfemale(u)) {
		if (u->body == 0)
			ciword = 0x822;
		goto adjust;
	}
	if (ciword == 0x825 || ciword == 0x84c || ciword == 0x84b) {
check:
		if (u->body == 0 || baselook(u->body & 0xfff) == 0x1ad)
			goto adjust;
	}
	switch (baselook(u->body & 0xfff)) {
	case 0:
		if (u->legs)
			ciword = 0x84d;
		else if (u->feet)
			ciword = 0x84e;
		else
			ciword = 0x835;
		break;
	case 0x1ad:
		if (u == &units[0])
			ciword = 0x82e;
		break;
	case 0x1ae:
		ciword = 0x831;
		break;
	case 0x1af:
		ciword = 0x83f;
		break;
	case 0x1b0:
		ciword = 0x834;
		break;
	case 0x1b1:
		ciword = 0x842;
		break;
	case 0x1b2:
		ciword = 0x849;
		break;
	case 0x1b3:
		if (ciword != 0x847)
			ciword = 0x848;
		break;
	case 0x1b4:
		ciword = 0x84a;
		break;
	}
adjust:
	if (ciword == 0x82d) {
		if (u->cloak == 0)
			ciword = 0x833;
	} else if (ciword == 0x823 || ciword == 0x828 || ciword == 0x836) {
		if (u->cloak == 0)
			ciword = 0x83e;
	} else if (ciword == 0x824) {
		if (u->cloak == 0)
			ciword = 0x853;
	}
	ciword += indexof(u) << 16;
	return ciword;
}

