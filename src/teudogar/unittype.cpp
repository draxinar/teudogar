void
buildparts(void)
{
	part1 = 0xff;
	part8 = 0xff;
	for (parti = 0; parti < 22; parti++) {
		parts[parti].type = ((Recipe *)(recipes + 0x20))[parti].type;
		parts[parti].hidering = 0;
		for (partj = 0; partj < 5; partj++) {
			partk = ((Recipe *)(recipes + 0x20))[parti].parts[partj];
			if (partj == 0) {
				partf7 = parts[parti].type;
				memcpy(&parts[parti], &partdefs[partk], sizeof(Part));
				parts[parti].type = partf7;
			} else if (partk) {
				if (partdefs[partk].noun)
					parts[parti].noun = partdefs[partk].noun;
				if (partdefs[partk].spare)
					parts[parti].spare = partdefs[partk].spare;
				if (partdefs[partk].cansit == 0)
					parts[parti].cansit = 0;
				if (partk == 51)
					parts[parti].hidering |= 1;
				if (partdefs[partk].text)
					parts[parti].text = partdefs[partk].text;
			}
		}
		if (parts[parti].type == 1)
			part1 = parti;
		else if (parts[parti].type == 8)
			part8 = parti;
	}
	if (part1 == 0xff || part8 == 0xff) {
		part1 = 0xff;
		part8 = 0xff;
	}
	memcpy(&parts[22], &partdefs[0], sizeof(Part));
	parts[22].type = 0x13;
}

