// Sold writes the C file that gives the port the bytes which mark each
// copy of the game sold, as make original's dd and cmd/seal give them to
// the Watcom builds.
//
// Usage:
//
//	sold sold.txt teudogar.exe
//
// sold.txt lists the runs of those bytes (src/teudogar/sold.txt), one a
// line: the address and the length of the run in teudogar.exe, its
// offset in the object that holds it, and that object as C declares it,
// an array of char or a struct. Sold prints on standard output a C file
// whose function soldinit copies each run from teudogar.exe into its
// object, at that offset. cmd/seal checks the objects and the offsets
// against the link map of make original. The file holds the release's
// licence bytes, so make writes it below build/, which git ignores.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"io"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/draxinar/teudogar/internal/pe"
)

func usage() {
	fmt.Fprintf(os.Stderr, "usage: sold sold.txt teudogar.exe\n")
	os.Exit(2)
}

func main() {
	log.SetFlags(0)
	log.SetPrefix("sold: ")
	flag.Usage = usage
	flag.Parse()
	if flag.NArg() != 2 {
		usage()
	}
	a := flag.Args()
	runs, err := readRuns(a[0])
	if err != nil {
		log.Fatal(err)
	}
	exe, err := os.ReadFile(a[1])
	if err != nil {
		log.Fatal(err)
	}
	w := bufio.NewWriter(os.Stdout)
	if err := write(w, runs, exe); err != nil {
		log.Fatal(err)
	}
	if err := w.Flush(); err != nil {
		log.Fatal(err)
	}
}

// A run is a line of sold.txt: the address and the length of the bytes
// in teudogar.exe, their offset in the object that holds them, and the
// object's name and declaration in C.
type run struct {
	addr uint32
	n    int
	off  int
	name string
	decl string
}

func readRuns(name string) ([]run, error) {
	f, err := os.Open(name)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	return parseRuns(f, name)
}

func parseRuns(r io.Reader, name string) ([]run, error) {
	var runs []run
	sc := bufio.NewScanner(r)
	for line := 1; sc.Scan(); line++ {
		fs := strings.Fields(sc.Text())
		if len(fs) == 0 {
			continue
		}
		if len(fs) < 5 {
			return nil, fmt.Errorf("%s:%d: want an address, a length, an offset, and a declaration", name, line)
		}
		addr, err1 := strconv.ParseUint(fs[0], 16, 32)
		n, err2 := strconv.Atoi(fs[1])
		off, err3 := strconv.Atoi(fs[2])
		if err1 != nil || err2 != nil || err3 != nil || n <= 0 || off < 0 {
			return nil, fmt.Errorf("%s:%d: %q, want an address in hex, a length, and an offset", name, line, sc.Text())
		}
		decl := strings.Join(fs[3:], " ")
		typ := strings.Join(fs[3:len(fs)-1], " ")
		obj := fs[len(fs)-1]
		ok := len(fs) == 6 && fs[3] == "struct"
		if strings.HasSuffix(obj, "[]") {
			obj = strings.TrimSuffix(obj, "[]")
			ok = typ == "char" || typ == "unsigned char"
		}
		if obj == "" || !ok {
			return nil, fmt.Errorf("%s:%d: declaration %q, want an array of char or a struct", name, line, decl)
		}
		runs = append(runs, run{uint32(addr), n, off, obj, decl})
	}
	return runs, sc.Err()
}

// write writes the C file of runs, with their bytes from exe.
func write(w io.Writer, runs []run, exe []byte) error {
	f, err := pe.Parse(exe)
	if err != nil {
		return err
	}
	decls := map[string]string{}
	var copies []string
	var tables []string
	for i, r := range runs {
		if d, ok := decls[r.name]; ok && d != r.decl {
			return fmt.Errorf("%s declared as %q and as %q", r.name, d, r.decl)
		}
		decls[r.name] = r.decl
		b := f.Bytes(r.addr-f.Opt.ImageBase, r.n)
		if b == nil {
			return fmt.Errorf("%d bytes at %08x outside the sections' data", r.n, r.addr)
		}
		var s strings.Builder
		fmt.Fprintf(&s, "static const unsigned char run%d[%d] = {", i, r.n)
		for j, c := range b {
			if j%12 == 0 {
				s.WriteString("\n\t")
			} else {
				s.WriteString(" ")
			}
			fmt.Fprintf(&s, "0x%02x,", c)
		}
		s.WriteString("\n};\n")
		tables = append(tables, s.String())
		addr := "&" + r.name
		if strings.HasSuffix(r.decl, "[]") {
			addr = r.name
		}
		copies = append(copies, fmt.Sprintf("\tmemcpy((unsigned char *)%s + %d, run%d, sizeof run%d);\n",
			addr, r.off, i, i))
	}
	names := make([]string, 0, len(decls))
	for n := range decls {
		names = append(names, n)
	}
	sort.Strings(names)
	fmt.Fprintf(w, "/* Generated by cmd/sold from src/teudogar/sold.txt and the release's teudogar.exe. */\n\n")
	fmt.Fprintf(w, "#include <string.h>\n\n")
	for _, n := range names {
		fmt.Fprintf(w, "extern %s;\n", decls[n])
	}
	fmt.Fprintf(w, "\nvoid soldinit(void);\n\n")
	for _, t := range tables {
		fmt.Fprintf(w, "%s\n", t)
	}
	fmt.Fprintf(w, "void\nsoldinit(void)\n{\n")
	for _, c := range copies {
		fmt.Fprint(w, c)
	}
	fmt.Fprintf(w, "}\n")
	return nil
}
